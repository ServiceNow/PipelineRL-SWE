CONDA_EXE=${CONDA_EXE:-/opt/conda/bin/conda}
COLLECTOR_ENV=${COLLECTOR_ENV:-pipeline-rl}
JOB_NPROC=${JOB_NPROC:-5}
TRAIN_NPROC=${TRAIN_NPROC:-4}
SNAPSHOT=${SNAPSHOT:-1}
